#define VPP_HWIO_INM(reg, field)	((mmio_read_32(reg) & field##_BMSK) >> field##_SHFT)

/* Bit format documented in the fusing guide. */
#define VPP_CLV_QUOT_OFFSET_PACK_FACTOR		5
#define VPP_APC_VOLTAGE_VALUE_BMSK		0x1f
#define VPP_APC_SIGN_BMSK			0x20
#define VPP_APC_OLV_PACKING_FACTOR		8

#define VPP_OLV_SIGN(val)	(((val) & VPP_APC_SIGN_BMSK) ? -1 : 1)
#define VPP_OLV_VAL(val)	(((val) & VPP_APC_VOLTAGE_VALUE_BMSK) * VPP_APC_OLV_PACKING_FACTOR)
#define VPP_OLV(val)		(VPP_OLV_VAL(val) * VPP_OLV_SIGN(val))

