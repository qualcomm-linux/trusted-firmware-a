#define HWIO_TCSR_SS_XPU_NON_SEC_INTR1_RMSK 0x07ffffff

#define HWIO_TCSR_SS_XPU_NON_SEC_INTR0_ENABLE_ADDR \
	(TCSR_TCSR_REGS_REG_BASE + 0x2040)
