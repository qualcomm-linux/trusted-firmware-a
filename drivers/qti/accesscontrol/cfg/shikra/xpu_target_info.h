#define HWIO_TCSR_SS_XPU_SEC_INTR1_RMSK 0x07ffffff

#define HWIO_TCSR_SS_XPU_SEC_INTR0_ENABLE_ADDR \
	(TCSR_TCSR_REGS_REG_BASE + 0x4040)
#define HWIO_TCSR_SS_XPU_SEC_INTR0_ENABLE_RMSK 0xffffffff

#define HWIO_TCSR_SS_XPU_SEC_INTR1_ENABLE_ADDR \
	(TCSR_TCSR_REGS_REG_BASE + 0x4044)
#define HWIO_TCSR_SS_XPU_SEC_INTR1_ENABLE_RMSK 0x07ffffff

