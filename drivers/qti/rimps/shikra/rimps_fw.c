struct rimps_fw_region {
	const uint32_t *values;
	uint32_t count;
	uintptr_t base;
};

static const struct rimps_fw_region rimps_fw_regions[] = {
	{ rimps_fw_instruction, ARRAY_SIZE(rimps_fw_instruction), RIMPS_EPSS_BASE },
	{ rimps_fw_data, ARRAY_SIZE(rimps_fw_data), RIMPS_EPSS_SHARED_DATA_BASE },
};

void rimps_fw_load(void)
{
	const struct rimps_fw_region *region;
	uint32_t i, j;

	for (i = 0U; i < ARRAY_SIZE(rimps_fw_regions); i++) {
		region = &rimps_fw_regions[i];
		for (j = 0U; j < region->count; j++)
			mmio_write_32(region->base + 4U * j, region->values[j]);
	}
}
