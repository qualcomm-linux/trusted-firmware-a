/*
 * Generic address-translator HWIO_INXF/HWIO_INXI macros, used by the
 * common driver's address-translation logic in icbcfg_query.c. These are
 * not chip-specific and are reused unchanged across all targets.
 */
#define HWIO_INXI(base, index, stride) \
	(*(volatile uint32_t *)((base) + ((index) * (stride))))
#define HWIO_INXF(base, index, stride, mask, shift) \
	((HWIO_INXI(base, index, stride) & (mask)) >> (shift))

