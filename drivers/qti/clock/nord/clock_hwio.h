/*
 * PLL enable-vote helpers used by the BSP data. Mirror the vendor
 * PLL_VOTE() macro but expand to curated, per-domain names. Each yields a
 * { addr, mask } pair for a struct clock_register_mask.
 */
#define PLL_VOTE(x) \
	{ GCC_APCS_TZ_PLL_BRANCH_ENA_VOTE, \
	  GCC_APCS_TZ_PLL_BRANCH_ENA_VOTE_##x##_BMSK }
#define NE_PLL_VOTE(x) \
	{ NE_GCC_APCS_TZ_PLL_BRANCH_ENA_VOTE, \
	  NE_GCC_APCS_TZ_PLL_BRANCH_ENA_VOTE_##x##_BMSK }
#define NW_PLL_VOTE(x) \
	{ NW_GCC_APCS_TZ_PLL_BRANCH_ENA_VOTE, \
	  NW_GCC_APCS_TZ_PLL_BRANCH_ENA_VOTE_##x##_BMSK }
