/*
 * Branch/PLL enable-vote field-mask helpers used by the configuration data.
 * VOTE*(x) yields a { addr, mask } pair for a struct clock_register_mask.
 * PLL_VOTE(x) yields an { addr, mask } pair for the GPLL ENA vote.
 */
#define VOTE(x) \
	{ GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE, \
	  GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_##x##_BMSK }
#define VOTE_0(x)	VOTE(x)
#define VOTE_1(x) \
	{ GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_1, \
	  GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_1_##x##_BMSK }
#define VOTE_2(x) \
	{ GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_2, \
	  GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_2_##x##_BMSK }
#define PLL_VOTE(x) \
	{ GCC_APCS_TZ_GPLL_ENA_VOTE, \
	  GCC_APCS_TZ_GPLL_ENA_VOTE_##x##_BMSK }

