/*
 * Branch/PLL enable-vote field-mask helpers used by the BSP data. These mirror
 * the vendor VOTE()/PLL_VOTE_MASK() macros but expand to the curated names
 * below. CLOCK_VOTE*(x) yields a { addr, mask } pair for a struct
 * clock_register_mask; CLOCK_PLL_VOTE_MASK(x) yields just the mask.
 */
#define CLOCK_VOTE(x) \
	{ CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE, \
	  CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_##x##_BMSK }
#define CLOCK_VOTE_0(x)		CLOCK_VOTE(x)
#define CLOCK_VOTE_1(x) \
	{ CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_1, \
	  CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_1_##x##_BMSK }
#define CLOCK_VOTE_2(x) \
	{ CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_2, \
	  CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_2_##x##_BMSK }
#define CLOCK_VOTE_3(x) \
	{ CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_3, \
	  CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_3_##x##_BMSK }
#define CLOCK_VOTE_4(x) \
	{ CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_4, \
	  CLOCK_GCC_APCS_TZ_CLOCK_BRANCH_ENA_VOTE_4_##x##_BMSK }
#define CLOCK_PLL_VOTE_MASK(x) \
	CLOCK_GCC_APCS_TZ_PLL_BRANCH_ENA_VOTE_##x##_BMSK

